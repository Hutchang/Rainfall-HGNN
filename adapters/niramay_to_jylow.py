"""
adapters/niramay_to_jylow.py — the FR-301 adapter.

Reads Niramay's Sydney gauge data (source, unmodified) and writes the
Jylow-format derived artifacts that `src/raingauge/utils.py:load_raingauge_dataset`
expects, implementing `docs/baseline-reconciliation/DATA_CONTRACT.md` exactly:

  source (never modified)
    <source>/raw/*.csv                 timestamp,station_id,rainfall_mm (hourly, long)
    <source>/station_metadata.csv      headerless: name,id,network,latitude,longitude
  derived (written fresh each run; database/ is gitignored)
    <out>/{year}/weather_station_data_{year}.csv   timestamp,stationId,value
    <out>/{year}/weather_stations_{year}.csv       id,latitude,longitude,deviceId,name
    <out>/ADAPTER_MANIFEST.json                    every count, exclusion and decision
    <split-out>                                    Niramay's reference fold assignment
                                                   (FR-303), Jylow split_info shape

Contract decisions implemented here (see DATA_CONTRACT.md §1/§4):
  - rainfall values pass through UNSCALED (the unit question is parked; Jylow's
    ×12 is neutralised loader-side via `accumulation_minutes`, not here)
  - timestamps are rewritten to the literal "%Y-%m-%dT%H:%M:00+08:00" shape that
    Jylow's strptime demands; the +08:00 is cosmetic (Jylow discards it) — the
    data is NOT shifted to Singapore time
  - NaN observations become row absence (Jylow re-derives NaN from the gap)
  - parked station ids are EXCLUDED with cause, never silently dropped
  - duplicate metadata registrations collapse to one row per id (keep='first',
    file order — deterministic; every collapsed row is recorded in the manifest)
  - the reference split is generated by importing Niramay's own
    `data.sampling.stratified_spatial_kfold` and replaying `data/loader.py`'s
    exact station_meta construction (uptime filter, NO metadata dedup, seed 123),
    then reconciled to one-row-per-id with precedence test > validation > train

Run from the repo root:
    .venv/Scripts/python.exe adapters/niramay_to_jylow.py
"""

import argparse
import glob
import json
import sys
from pathlib import Path

import pandas as pd

# Parked per DATA_CONTRACT.md §4 — excluded with cause, not silently.
DEFAULT_EXCLUDE = {
    "563083": "BOM-side id collision: one series, two real distant candidate locations",
    "567163": "BOM-side id collision: one series, two real distant candidate locations",
    "563086": "listed coordinate is a copy of 212285's; true location unknown",
}

UPTIME_THRESHOLD = 0.9  # matches both configs (Niramay data.uptime_threshold, Jylow filters.uptime_threshold)
SPLIT_SEED = 123  # matches both configs
N_SPLITS = 5


def resolve_source() -> Path:
    """Same resolution order as tests/conftest.py (NFR-002)."""
    import os

    candidates = []
    env = os.environ.get("SYDNEY_GAUGE_ROOT")
    if env:
        candidates.append(Path(env))
    here = Path(__file__).resolve().parent.parent
    candidates.append(here.parent / "COMP3888-niramay" / "database" / "australia")
    candidates.append(here / "database" / "australia")
    for c in candidates:
        if (c / "station_metadata.csv").is_file() and (c / "raw").is_dir():
            return c
    raise FileNotFoundError(
        "Sydney gauge data not found. Set SYDNEY_GAUGE_ROOT or create the "
        "niramay worktree: git worktree add ../COMP3888-niramay niramay-clone"
    )


def load_source(source: Path) -> tuple[pd.DataFrame, pd.DataFrame]:
    files = sorted(glob.glob(str(source / "raw" / "*.csv")))
    if not files:
        raise FileNotFoundError(f"no raw station CSVs under {source / 'raw'}")
    long_df = pd.concat((pd.read_csv(f) for f in files), ignore_index=True)
    long_df["timestamp"] = pd.to_datetime(long_df["timestamp"])
    long_df["station_id"] = long_df["station_id"].astype(str)

    dup = long_df.duplicated(subset=["timestamp", "station_id"])
    if dup.any():
        raise ValueError(
            f"{dup.sum()} duplicate (timestamp, station_id) observations — "
            "one-series-per-id assumption violated; refusing to continue"
        )

    meta = pd.read_csv(
        source / "station_metadata.csv",
        header=None,
        names=["name", "id", "network", "latitude", "longitude"],
    )
    meta["id"] = meta["id"].astype(str)
    return long_df, meta


def reference_split(
    source: Path, long_df: pd.DataFrame, meta_all: pd.DataFrame, manifest: dict
) -> list[dict]:
    """Replay data/loader.py + train.py's split exactly, then reconcile to
    one-row-per-id (FR-303). Imports Niramay's own sampler — no reimplementation."""
    niramay_root = source.parent.parent  # <source>=.../database/australia
    sys.path.insert(0, str(niramay_root))
    from data.sampling import stratified_spatial_kfold  # Niramay's, verbatim

    # loader.py:32-54 verbatim: pivot -> uptime filter -> meta isin (NO dedup) -> order
    wide = long_df.pivot(index="timestamp", columns="station_id", values="rainfall_mm")
    uptime = wide.notna().mean(axis=0)
    keep = uptime[uptime >= UPTIME_THRESHOLD].index
    station_meta = meta_all[meta_all["id"].isin(keep)].copy().reset_index(drop=True)
    station_meta["order"] = range(len(station_meta))
    manifest["reference_split"] = {
        "stations_passing_uptime": len(keep),
        "metadata_rows_entering_sampler": len(station_meta),
        "sampler": "data.sampling.stratified_spatial_kfold (Niramay, imported)",
        "seed": SPLIT_SEED,
        "n_splits": N_SPLITS,
    }

    folds = stratified_spatial_kfold(station_meta, n_splits=N_SPLITS, seed=SPLIT_SEED)

    # Reconcile duplicate-id rows: Niramay's sampler partitions metadata ROWS, so a
    # duplicated id can land in two splits of the same fold. One-row-per-id needs one
    # assignment; precedence test > validation > train keeps held-out targets held out.
    straddlers: dict[str, list] = {}
    clean_folds = []
    for f in folds:
        test = list(dict.fromkeys(str(s) for s in f["ml"]["test"]))
        val = [
            s
            for s in dict.fromkeys(str(s) for s in f["ml"]["validation"])
            if s not in test
        ]
        train = [
            s
            for s in dict.fromkeys(str(s) for s in f["ml"]["train"])
            if s not in test and s not in val
        ]
        moved = (
            set(str(s) for s in f["ml"]["train"])
            | set(str(s) for s in f["ml"]["validation"])
        ) & set(test)
        moved |= set(str(s) for s in f["ml"]["train"]) & set(val)
        if moved:
            straddlers[f"fold_{f['fold_index']}"] = sorted(moved)
        clean_folds.append(
            {
                "fold_index": f["fold_index"],
                "ml": {"train": train, "validation": val, "test": test},
            }
        )
    manifest["reference_split"][
        "duplicate_id_straddlers_resolved_test_gt_val_gt_train"
    ] = straddlers
    return clean_folds


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", type=Path, default=None)
    ap.add_argument("--out", type=Path, default=Path("database/raingauge_nea_data"))
    ap.add_argument(
        "--split-out", type=Path, default=Path("database/sydney_split_info.json")
    )
    args = ap.parse_args()

    source = args.source or resolve_source()
    print(f"source:  {source}")
    print(f"out:     {args.out}")

    manifest: dict = {
        "contract": "docs/baseline-reconciliation/DATA_CONTRACT.md",
        "source": str(source),
        "units": "rainfall values passed through UNSCALED (unit provenance parked, "
        "DATA_CONTRACT.md §4); Jylow's x12 must be neutralised via "
        "dataset_parameters.gauge_accumulation_minutes: 60",
        "timezone": "timestamps reformatted to literal +08:00 shape for Jylow's parser; "
        "NOT shifted to Singapore time; source tz remains undocumented",
    }

    long_df, meta_all = load_source(source)
    data_ids = sorted(long_df["station_id"].unique())
    manifest["input"] = {
        "raw_rows": len(long_df),
        "station_ids_with_data": len(data_ids),
        "metadata_rows_total": len(meta_all),
        "metadata_unique_ids": int(meta_all["id"].nunique()),
    }
    print(
        f"input: {len(long_df):,} rows, {len(data_ids)} station ids, "
        f"{len(meta_all)} metadata rows ({meta_all['id'].nunique()} unique ids)"
    )

    # Reference split BEFORE exclusions — it must reproduce Niramay's run as-was.
    folds = reference_split(source, long_df, meta_all, manifest)

    # --- Exclusions (parked ids) ---------------------------------------------
    excluded_present = {
        sid: why for sid, why in DEFAULT_EXCLUDE.items() if sid in data_ids
    }
    manifest["exclusions"] = excluded_present
    long_df = long_df[~long_df["station_id"].isin(excluded_present)]
    for f in folds:
        for k in ("train", "validation", "test"):
            f["ml"][k] = [s for s in f["ml"][k] if s not in excluded_present]

    # --- Metadata: restrict to stations with data, dedup to one row per id ---
    meta = meta_all[meta_all["id"].isin(long_df["station_id"].unique())].copy()
    dup_mask = meta.duplicated(subset=["id"], keep="first")
    collapsed = meta[meta["id"].isin(meta.loc[dup_mask, "id"])]
    manifest["metadata_dedup"] = {
        "rule": "drop_duplicates(id, keep='first') in file order",
        "ids_collapsed": {
            sid: grp[["name", "network", "latitude", "longitude"]].to_dict("records")
            for sid, grp in collapsed.groupby("id")
        },
    }
    meta = meta.drop_duplicates(subset=["id"], keep="first").reset_index(drop=True)

    no_meta = sorted(set(long_df["station_id"].unique()) - set(meta["id"]))
    if no_meta:
        manifest["excluded_no_metadata"] = no_meta
        long_df = long_df[~long_df["station_id"].isin(no_meta)]
        print(
            f"WARNING: {len(no_meta)} station(s) have data but no metadata row "
            f"— excluded: {no_meta}"
        )

    # --- Emit per-year Jylow-format files -------------------------------------
    long_df = long_df.dropna(subset=["rainfall_mm"])  # NaN -> row absence
    long_df = long_df.sort_values(["timestamp", "station_id"])
    out_stamp = long_df["timestamp"].dt.strftime("%Y-%m-%dT%H:%M:00+08:00")
    emit = pd.DataFrame(
        {
            "timestamp": out_stamp,
            "stationId": long_df["station_id"],
            "value": long_df["rainfall_mm"],
        }
    )
    emit["year"] = long_df["timestamp"].dt.year.values

    stations_out = pd.DataFrame(
        {
            "id": meta["id"],
            "latitude": meta["latitude"],
            "longitude": meta["longitude"],
            "deviceId": meta["id"],  # required-but-unused by Jylow's loader
            "name": meta["name"],
        }
    )

    manifest["output"] = {"final_station_count": int(meta["id"].nunique()), "years": {}}
    for year, grp in emit.groupby("year"):
        ydir = args.out / str(year)
        ydir.mkdir(parents=True, exist_ok=True)
        grp.drop(columns="year").to_csv(
            ydir / f"weather_station_data_{year}.csv", index=False
        )
        stations_out.to_csv(ydir / f"weather_stations_{year}.csv", index=False)
        manifest["output"]["years"][str(year)] = {
            "rows": len(grp),
            "stations": int(grp["stationId"].nunique()),
        }
        print(f"  {year}: {len(grp):,} rows, {grp['stationId'].nunique()} stations")

    args.split_out.parent.mkdir(parents=True, exist_ok=True)
    with open(args.split_out, "w") as fh:
        json.dump(
            {
                "provenance": manifest["reference_split"],
                "exclusions_applied": sorted(excluded_present),
                "folds": folds,
            },
            fh,
            indent=1,
        )
    print(f"reference split -> {args.split_out}")

    with open(args.out / "ADAPTER_MANIFEST.json", "w") as fh:
        json.dump(manifest, fh, indent=1, default=str)
    print(f"manifest -> {args.out / 'ADAPTER_MANIFEST.json'}")
    print(
        f"final station count: {meta['id'].nunique()} "
        f"(excluded with cause: {sorted(excluded_present) + no_meta})"
    )


if __name__ == "__main__":
    main()
